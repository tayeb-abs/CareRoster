function escapeHtml(value: string) {
  return value.replace(/[&<>"']/g, (character) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    "\"": "&quot;",
    "'": "&#39;",
  })[character]!);
}

function localDate(value: string, language: AppLanguage, options: Intl.DateTimeFormatOptions) {
  return new Intl.DateTimeFormat(language, { ...options, timeZone: "UTC" })
    .format(new Date(`${value}T00:00:00.000Z`));
}

function number(value: number, language: AppLanguage) {
  return new Intl.NumberFormat(language).format(value);
}

function renderShiftDetails(rows: ExportScheduleDetail[], language: AppLanguage) {
  const headers = ["Date", "Nurse", "Shift name", "Start time", "End time", "Total hours"]
    .map((label) => `<th>${escapeHtml(translateText(label, language))}</th>`).join("");
  const body = rows.map((row) => `<tr><td>${escapeHtml(localDate(row.date, language, { dateStyle: "medium" }))}</td><td>${escapeHtml(row.nurseName)}</td><td>${escapeHtml(row.shiftName)}</td><td>${escapeHtml(row.startTime ? formatShiftTime(row.startTime, language) : "—")}</td><td>${escapeHtml(row.endTime ? formatShiftTime(row.endTime, language) : "—")}</td><td>${number(row.totalHours, language)}</td></tr>`).join("");
  return `<section class="shift-detail-section"><h2>${escapeHtml(translateText("Assigned shifts and actual hours", language))}</h2><table class="report-table"><thead><tr>${headers}</tr></thead><tbody>${body || `<tr><td colspan="6">${escapeHtml(translateText("No shift assignments", language))}</td></tr>`}</tbody></table></section>`;
}

function renderMetadata(language: AppLanguage, branding: ExportBranding, range: string, title: string) {
  const clinic = branding.clinic ?? defaultClinicBrand;
  const logo = clinic.logoDataUrl
    ? `<img class="clinic-logo" src="${escapeHtml(clinic.logoDataUrl)}" alt="">`
    : `<span class="clinic-mark" aria-hidden="true">E</span>`;
  const details = [
    clinic.address,
    clinic.phoneNumber,
    clinic.departmentName && `${translateText("Department", language)}: ${clinic.departmentName}`,
    clinic.headNurseName && `${translateText("Head Nurse", language)}: ${clinic.headNurseName}`,
  ].filter(Boolean).map((value) => escapeHtml(value!)).join(" · ");
  const generatedAt = branding.generatedAt ?? new Date().toISOString();
  return `<header class="document-header">
    <div class="brand-row">${logo}<div><strong>${escapeHtml(clinicName(clinic, language))}</strong><div class="system-name">CareRoster</div>${details ? `<div class="clinic-details">${details}</div>` : ""}</div></div>
    <h1>${escapeHtml(title)}</h1>
    <p class="week-range">${escapeHtml(translateText("Schedule period", language))}: ${escapeHtml(range)}</p>
    <div class="document-meta"><span>${escapeHtml(translateText("Generated", language))}: ${escapeHtml(new Intl.DateTimeFormat(language, { dateStyle: "medium", timeStyle: "short" }).format(new Date(generatedAt)))}</span><span>${escapeHtml(translateText("Generated by", language))}: ${escapeHtml(branding.generatedBy || "—")}</span></div>
  </header>`;
}

