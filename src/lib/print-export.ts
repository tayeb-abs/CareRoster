function printableDocument(documentHtml: string) {
  const popup = window.open("", "_blank");
  if (!popup) return false;
  popup.document.open();
  popup.document.write(documentHtml);
  popup.document.close();
  const printWhenReady = () => {
    if (popup.closed) return;
    popup.focus();
    popup.print();
  };
  void Promise.all([
    new Promise<void>((resolve) => window.setTimeout(resolve, 400)),
    popup.document.fonts?.ready.then(() => undefined) ?? Promise.resolve(),
  ]).then(printWhenReady);
  return true;
}

function renderRosterTable(roster: WeeklyRoster, language: AppLanguage) {
  const nurseHeader = language === "ar" ? "الاسم" : "Nurse";
  const days = roster.days.map((day) => `<th class="${day.isFriday ? "friday-cell" : ""}">${escapeHtml(day.label)}</th>`).join("");
  const rows = roster.nurses.map((nurse) => {
    const nurseColor = /^#[0-9a-f]{6}$/i.test(nurse.color) ? nurse.color : "#176b9a";
    const cells = roster.days.map((day) => {
      const shift = nurse.shifts.get(day.date);
      if (!shift) return `<td class="${day.isFriday ? "friday-cell" : ""}">—</td>`;
      const typeClass = `shift-${shift.type.toLowerCase()}`;
      return `<td class="${typeClass}${day.isFriday ? " friday-cell" : ""}">${escapeHtml(shift.label)}</td>`;
    }).join("");
    const nurseClass = nurse.level === "SENIOR" ? "nurse-senior" : "";
    const seniorBadge = nurse.level === "SENIOR" ? "⭐ " : "";
    return `<tr><td class="nurse-cell ${nurseClass}"><i class="nurse-dot" style="background:${nurseColor}"></i>${seniorBadge}${escapeHtml(nurse.name)}</td>${cells}</tr>`;
  }).join("");
  const emptyRow = `<tr><td colspan="${roster.days.length + 1}">${escapeHtml(translateText("No schedule yet", language))}</td></tr>`;
  return `<table class="roster-table"><thead><tr><th>${escapeHtml(nurseHeader)}</th>${days}</tr></thead><tbody>${rows || emptyRow}</tbody></table>`;
}

export function printScheduleExport(input: {
  language: AppLanguage;
  startDate: string;
  endDate: string;
  assignments: ExportAssignment[];
  nurses?: RosterNurseInput[];
  period?: ScheduleReportPeriod;
  warnings?: ExportWarning[];
} & ExportBranding) {
  return printableDocument(renderScheduleExportDocument(input));
}

export function renderScheduleExportDocument(input: {
  language: AppLanguage;
  startDate: string;
  endDate: string;
  assignments: ExportAssignment[];
  nurses?: RosterNurseInput[];
  period?: ScheduleReportPeriod;
  warnings?: ExportWarning[];
} & ExportBranding) {
  const { language, startDate, endDate, assignments, warnings = [] } = input;
  const period = input.period ?? "weekly";
  const title = translateText(period === "monthly" ? "Monthly schedule" : "Weekly schedule", language);
  const range = `${translateText("From", language)} ${localDate(startDate, language, { dateStyle: "long" })} · ${translateText("To", language)} ${localDate(endDate, language, { dateStyle: "long" })}`;
  const roster = buildWeeklyRoster(assignments, startDate, language, endDate, input.nurses);
  const warningRows = warnings.map((warning) => `<li><strong>${escapeHtml(translateText("HIGH PRIORITY", language))}</strong> · ${escapeHtml(localDate(warning.date, language, { dateStyle: "long" }))}: ${escapeHtml(translateText(warning.message, language))}</li>`).join("");
  const warningSection = warningRows
    ? `<section class="warnings"><h2>${escapeHtml(translateText("Schedule warnings", language))}</h2><ul>${warningRows}</ul></section>`
    : "";
  const content = `${renderMetadata(language, input, range, title)}${renderRosterTable(roster, language).replace('<table class="roster-table">', `<table class="roster-table${period === "monthly" ? " monthly-roster" : ""}">`)}${warningSection}`;
  return renderDocument(language, title, content, input.orientation ?? "landscape", period);
}

export function printReportsExport(input: {
  language: AppLanguage;
  year: number;
  month: number;
  rows: ExportFairnessRow[];
  assignments?: ExportAssignment[];
  warnings?: ExportWarning[];
} & ExportBranding) {
  return printableDocument(renderReportsExportDocument(input));
}

export function renderReportsExportDocument(input: {
  language: AppLanguage;
  year: number;
  month: number;
  rows: ExportFairnessRow[];
  assignments?: ExportAssignment[];
  warnings?: ExportWarning[];
} & ExportBranding) {
  const { language, year, month, rows, warnings = [] } = input;
  const title = translateText("Reports & statistics", language);
  const clinic = input.clinic ?? defaultClinicBrand;
  const start = new Date(Date.UTC(year, month - 1, 1)).toISOString().slice(0, 10);
  const end = new Date(Date.UTC(year, month, 0)).toISOString().slice(0, 10);
  const headings = ["NAME", "WORKING DAYS", "TOTAL HOURS", "FRIDAY DUTY", "SENIOR FRIDAY ASSIGNMENTS", "REGULAR FRIDAY ASSIGNMENTS", "OFF-DAYS", "LEAVE"]
    .map((item) => `<th>${escapeHtml(translateText(item, language))}</th>`).join("");
  const bodyRows = rows.map((row) => `<tr>
    <td class="${row.nurseLevel === "SENIOR" ? "nurse-senior" : ""}">${row.nurseLevel === "SENIOR" ? "⭐ " : ""}${escapeHtml(row.nurseName)}</td>
    <td>${number(row.workingDays, language)}</td><td>${number(row.totalHours ?? 0, language)}</td><td>${number(row.fridayAssignments, language)}</td><td>${number(row.seniorFridayAssignments, language)}</td><td>${number(row.regularFridayAssignments, language)}</td><td>${number(row.offDays, language)}</td><td>${number(row.leaveDays, language)}</td>
  </tr>`).join("");
  const totals = rows.reduce((result, row) => ({
    work: result.work + row.workingDays,
    hours: result.hours + (row.totalHours ?? 0),
    friday: result.friday + row.fridayAssignments,
    seniorFriday: result.seniorFriday + row.seniorFridayAssignments,
    regularFriday: result.regularFriday + row.regularFridayAssignments,
    off: result.off + row.offDays,
    leave: result.leave + row.leaveDays,
  }), { work: 0, hours: 0, friday: 0, seniorFriday: 0, regularFriday: 0, off: 0, leave: 0 });
  const warningRows = warnings.map((warning) => `<li><strong>${escapeHtml(translateText("HIGH PRIORITY", language))}</strong> · ${escapeHtml(localDate(warning.date, language, { dateStyle: "long" }))}: ${escapeHtml(translateText(warning.message, language))}</li>`).join("");
  const monthRange = `${localDate(start, language, { dateStyle: "long" })} – ${localDate(end, language, { dateStyle: "long" })}`;
  const content = `<header class="document-header">
    <div class="brand-row">${clinic.logoDataUrl ? `<img class="clinic-logo" src="${escapeHtml(clinic.logoDataUrl)}" alt="">` : `<span class="clinic-mark">E</span>`}<div><strong>${escapeHtml(clinicName(clinic, language))}</strong></div></div>
    <h1>${escapeHtml(title)}</h1><p class="week-range">${escapeHtml(monthName(year, month, language))} · ${escapeHtml(monthRange)}</p>
    <div class="document-meta"><span>${escapeHtml(translateText("Generated", language))}: ${escapeHtml(new Intl.DateTimeFormat(language, { dateStyle: "medium", timeStyle: "short" }).format(new Date(input.generatedAt ?? new Date().toISOString())))}</span><span>${escapeHtml(translateText("Generated by", language))}: ${escapeHtml(input.generatedBy || "—")}</span></div>
    ${[clinic.address, clinic.phoneNumber, clinic.departmentName, clinic.headNurseName].filter(Boolean).length ? `<div class="clinic-details">${[clinic.address, clinic.phoneNumber, clinic.departmentName, clinic.headNurseName].filter(Boolean).map((value) => escapeHtml(value!)).join(" · ")}</div>` : ""}
  </header><table class="report-table"><thead><tr>${headings}</tr></thead><tbody>${bodyRows}</tbody>
      <tfoot><tr><th>${escapeHtml(translateText("Total", language))}</th><th>${number(totals.work, language)}</th><th>${number(totals.hours, language)}</th><th>${number(totals.friday, language)}</th><th>${number(totals.seniorFriday, language)}</th><th>${number(totals.regularFriday, language)}</th><th>${number(totals.off, language)}</th><th>${number(totals.leave, language)}</th></tr></tfoot></table>
    ${renderShiftDetails((input.assignments ?? []).filter((row) => row.type === "WORK").flatMap((assignment) =>
      assignment.shiftAssignments?.length
        ? assignment.shiftAssignments.map((shift) => ({ date: assignment.date, nurseName: assignment.nurseName, shiftName: shift.shiftName, startTime: shift.startTime, endTime: shift.endTime, totalHours: Number(shift.totalHours) }))
        : [{ date: assignment.date, nurseName: assignment.nurseName, shiftName: translateText("Shift not assigned", language), totalHours: 0 }],
    ), language)}
    ${warningRows ? `<section class="warnings"><h2>${escapeHtml(translateText("Schedule warnings", language))}</h2><ul>${warningRows}</ul></section>` : ""}`;
  return renderDocument(language, title, content, input.orientation ?? "landscape");
}
