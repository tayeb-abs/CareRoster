export function translateText(value: string, language: AppLanguage): string {
  if (language === "en") return value;
  const trimmed = value.trim();
  let translated: string | undefined = arabicMessages[trimmed] ?? arabicDays[trimmed];
  if (!translated) {
    const activeNurses = trimmed.match(/^(\d+) active nurses$/);
    const teamProfiles = trimmed.match(/^(\d+) team profiles$/);
    const shiftsThisWeek = trimmed.match(/^(\d+) shifts this week$/);
    const nursesScheduled = trimmed.match(/^(\d+) nurses scheduled$/);
    const shiftEntries = trimmed.match(/^(\d+) shift entries today$/);
    const exceptionCount = trimmed.match(/^(\d+) exceptions? recorded$/);
    translated = activeNurses?.[1] ? `${activeNurses[1]} ممرض نشط` :
      teamProfiles?.[1] ? `${teamProfiles[1]} ملفات للفريق` :
      shiftsThisWeek?.[1] ? `${shiftsThisWeek[1]} مناوبة هذا الأسبوع` :
      nursesScheduled?.[1] ? `${nursesScheduled[1]} ممرضين مجدولين` :
      shiftEntries?.[1] ? `${shiftEntries[1]} مناوبة اليوم` :
      exceptionCount?.[1] ? `${exceptionCount[1]} استثناء مسجل` : undefined;
  }
  if (!translated) return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

export function monthName(year: number, month: number, language: AppLanguage) {
  return new Intl.DateTimeFormat(language, { month: "long", year: "numeric", timeZone: "UTC" })
    .format(new Date(Date.UTC(year, month - 1, 1)));
}
